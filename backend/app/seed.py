def _simulation_channels(scenario: str, seconds: int, seed: int) -> tuple[dict, dict]:
    window = generate_window(scenario, 0, seconds, seed=seed)
    return window["channels"], window["sampling_rates"]


def _write_demo_csv(path: Path, scenario: str, seconds: int = 90, seed: int = 11) -> None:
    channels, rates = _simulation_channels(scenario, seconds, seed)
    n = int(seconds * FS)
    t = np.arange(n) / FS
    eda_t = np.arange(channels["eda"].size) / rates["eda"]
    resp_t = np.arange(channels["resp"].size) / rates["resp"]
    temp_t = np.arange(channels["temp"].size) / rates["temp"]
    acc_t = np.arange(channels["acc"].shape[0]) / rates["acc"]

    def interp(values, src_t):
        values = np.asarray(values, dtype=float)
        finite = np.isfinite(values)
        if finite.sum() < 2:
            return np.zeros_like(t)
        filled = np.interp(src_t, src_t[finite], values[finite])
        return np.interp(t, src_t, filled)

    frame = pd.DataFrame(
        {
            "time_s": np.round(t, 4),
            "ECG": np.round(channels["ecg"], 5),
            "EDA": np.round(interp(channels["eda"], eda_t), 5),
            "Resp": np.round(interp(channels["resp"], resp_t), 5),
            "Temp": np.round(interp(channels["temp"], temp_t), 5),
            "ACC_x": np.round(interp(channels["acc"][:, 0], acc_t), 5),
            "ACC_y": np.round(interp(channels["acc"][:, 1], acc_t), 5),
            "ACC_z": np.round(interp(channels["acc"][:, 2], acc_t), 5),
        }
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(path, index=False)


def _create_user(db: Session, name: str, email: str, password: str, role: str, share: bool) -> User:
    user = User(
        name=name,
        email=email,
        password_hash=hash_password(password),
        role=role,
        is_demo=True,
    )
    user.profile = Profile(
        display_name=name,
        organisation="AuraSense demonstration" if role != "individual" else None,
        share_aggregate=share,
        store_raw_signals=True,
        allow_baseline=True,
        baseline_min_sessions=5,
    )
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


def _session_for(
    db: Session, user: User, scenario: str, days_ago: float, duration: int, quality: float | None
) -> MonitoringSession:
    started = datetime.now(timezone.utc) - timedelta(days=days_ago)
    session = MonitoringSession(
        user_id=user.id,
        started_at=started,
        ended_at=started + timedelta(seconds=duration),
        data_source="simulated",
        scenario=scenario,
        status="completed",
        is_simulation=True,
        is_demo=True,
        duration_seconds=duration,
        quality_score=quality,
    )
    db.add(session)
    db.commit()
    db.refresh(session)
    return session


def _add_simulated_analysis(
    db: Session,
    user: User,
    scenario: str,
    days_ago: float,
    *,
    with_session: bool = True,
    seed: int = 3,
) -> AnalysisResult:
    seconds = 60
    channels, rates = _simulation_channels(scenario, seconds, seed)
    session = _session_for(db, user, scenario, days_ago, seconds, None) if with_session else None
    record, _ = analysis_service.analyse_channels(
        db,
        user,
        channels,
        rates,
        title=f"Simulated monitoring session — {scenario}",
        source_type="simulated",
        source_label=(
            f"Simulated {scenario} scenario ({seconds}s window). Illustrative synthetic signals, "
            "not a real measurement."
        ),
        duration=seconds,
        session_id=session.id if session else None,
        is_demo=True,
    )
    stamp = datetime.now(timezone.utc) - timedelta(days=days_ago)
    record.created_at = stamp
    if session:
        session.quality_score = record.quality_score
        session.quality_grade = record.quality_grade
        session.started_at = stamp - timedelta(seconds=seconds)
        session.ended_at = stamp
    db.commit()
    return record


def _seed_wesad_dataset(db: Session) -> Dataset | None:
    summary_path = settings.artifacts_dir / "dataset_summary.json"
    if not summary_path.exists():
        return None
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    dataset = Dataset(
        name="WESAD — local installation",
        source="UCI Machine Learning Repository (local copy, not redistributed)",
        description=(
            "Wearable Stress and Affect Detection (WESAD) dataset: 15 participants, chest and wrist devices, "
            "laboratory protocol with neutral, stress (TSST) and amusement conditions. AuraSense extracted "
            "60-second windows with 30-second stride and participant identifiers preserved for grouped evaluation."
        ),
        channels=json.dumps(
            {
                "chest": ["ECG", "EDA", "EMG", "Resp", "Temp", "ACC"],
                "wrist": ["BVP", "EDA", "TEMP", "ACC"],
            }
        ),
        sampling_rates=json.dumps(summary.get("sampling_rates", {})),
        participant_count=int(summary.get("participant_count", 15)),
        label_distribution=json.dumps(summary.get("class_distribution", {})),
        class_names=json.dumps(["neutral", "stress", "amusement"]),
        file_meta=json.dumps(
            {
                "windows": summary.get("windows"),
                "window_seconds": summary.get("window_seconds"),
                "step_seconds": summary.get("step_seconds"),
                "excluded_labels": summary.get("excluded_labels"),
                "missing_feature_percent": summary.get("missing_feature_percent"),
            }
        ),
        is_demo=False,
        is_reference=True,
    )
    db.add(dataset)
    db.commit()
    db.refresh(dataset)
    return dataset


def _seed_demo_datasets(db: Session) -> list[Dataset]:
    out = []
    for scenario, label in (("resting", "Resting reference recording"), ("arousal", "Arousal reference recording")):
        path = settings.storage_dir / "demo" / f"demo_{scenario}.csv"
        if not path.exists():
            _write_demo_csv(path, scenario, seconds=90, seed=7 if scenario == "resting" else 13)
        dataset = Dataset(
            name=f"Simulated {label}",
            source="AuraSense simulator (synthetic)",
            description=(
                "A 90-second synthetic recording generated by the AuraSense simulator for demonstrations. "
                "It is not a recording of a person and must not be treated as evidence about anyone's stress."
            ),
            file_path=str(path),
            file_meta=json.dumps({"rows": 22500, "sampling_rate_hz": FS, "is_simulation": True}),
            channels=json.dumps(["ecg", "eda", "resp", "temp", "acc"]),
            sampling_rates=json.dumps({"hz": FS}),
            participant_count=1,
            label_distribution=json.dumps({"neutral": 1} if scenario == "resting" else {"stress": 1}),
            class_names=json.dumps(["neutral", "stress"]),
            is_demo=True,
            is_reference=False,
        )
        db.add(dataset)
        out.append(dataset)
    db.commit()
    for dataset in out:
        db.refresh(dataset)
    return out


def _seed_experiments(db: Session, dataset: Dataset | None) -> None:
    metrics_path = settings.artifacts_dir / "metrics.json"
    if not metrics_path.exists():
        return
    metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
    for idx, result in enumerate(metrics.get("models", [])):
        payload = {
            **result.get("metrics", {}),
            "model": result.get("model"),
            "evaluation_strategy": metrics.get("evaluation_strategy"),
            "windows": metrics.get("windows"),
            "participants": metrics.get("participants"),
            "class_distribution": metrics.get("class_distribution", {}),
            "per_subject": result.get("per_subject", {}),
            "feature_importance": metrics.get("feature_importance", []),
            "best_model": metrics.get("best_model"),
        }
        experiment = ResearchExperiment(
            dataset_id=dataset.id if dataset else None,
            model_type=result.get("model", "model"),
            evaluation_strategy=metrics.get("evaluation_strategy", "GroupKFold by participant"),
            metrics=json.dumps(payload),
            model_version=metrics.get("best_model_version", ""),
            notes=(
                "Baseline evaluation produced by `python -m ml.train` on the local WESAD installation. "
                "Participants held out entirely from training in each fold."
            ),
            created_at=datetime.now(timezone.utc) - timedelta(days=14 - idx),
        )
        db.add(experiment)
    db.commit()


def seed_all(db: Session) -> None:
    settings.ensure_dirs()
    logger.info("Seeding AuraSense demonstration data")

    accounts = {
        role: _create_user(db, name, email, password, role, share=(role != "individual"))
        for role, (name, email, password) in _demo_users().items()
    }
    demo_user = accounts["individual"]

    cohort = []
    for idx, name in enumerate(COHORT_NAMES):
        cohort.append(
            _create_user(
                db,
                name,
                f"demo.participant{idx + 1:02d}@aurasense.app",
                settings.demo_cohort_password,
                "individual",
                share=True,
            )
        )

    wesad = _seed_wesad_dataset(db)
    demo_datasets = _seed_demo_datasets(db)
    _seed_experiments(db, wesad)

    scenarios = ["resting", "recovery", "arousal", "resting"]
    for idx, scenario in enumerate(scenarios):
        _add_simulated_analysis(
            db,
            demo_user,
            scenario,
            days_ago=[12.4, 8.2, 4.1, 1.3][idx],
            with_session=True,
            seed=20 + idx,
        )

    for idx, scenario in enumerate(["resting", "arousal"]):
        _add_simulated_analysis(
            db,
            accounts["researcher"],
            scenario,
            days_ago=6.5 - idx * 2,
            with_session=True,
            seed=60 + idx,
        )

    cohort_scenarios = ["resting", "arousal", "recovery", "activity", "resting", "arousal"]
    for idx, member in enumerate(cohort):
        count = 1 + (idx % 3)
        for run in range(count):
            days_ago = 2 + ((idx * 3 + run * 5) % 50)
            _add_simulated_analysis(
                db,
                member,
                cohort_scenarios[(idx + run) % len(cohort_scenarios)],
                days_ago=days_ago,
                with_session=False,
                seed=40 + idx + run,
            )

    # A second, analysed demonstration dataset so the Research Centre and Lab
    # both have a non-simulated-stream entry.
    for dataset in demo_datasets:
        try:
            frame = pd.read_csv(dataset.file_path)
            analysis_service.analyse_dataframe(
                db,
                demo_user,
                frame,
                title=dataset.name,
                source_type="demo_file",
                source_label=f"Dataset: {dataset.name} (synthetic demonstration recording)",
                dataset_id=dataset.id,
                is_demo=True,
            )
        except Exception:
            logger.exception("Could not analyse demo dataset %s", dataset.name)

    try:
        from .services.baseline import recalibrate

        recalibrate(db, demo_user)
    except Exception:
        logger.warning("Demo baseline could not be computed yet")

    try:
        from .services import reporting

        latest = db.scalars(
            select(AnalysisResult)
            .where(AnalysisResult.user_id == demo_user.id)
            .order_by(AnalysisResult.created_at.desc())
        ).first()
        if latest:
            reporting.analysis_report(db, demo_user, latest)
    except Exception:
        logger.exception("Demo PDF report generation failed")

    logger.info("Seeded %s users, %s demo datasets", len(cohort) + len(accounts), len(demo_datasets))


def seed_if_needed(db: Session) -> None:
    existing = db.scalars(select(User).limit(1)).first()
    if existing is not None:
        return
    seed_all(db)


def reset_and_seed(db: Session) -> None:
    for model in (
        Report,
        AnalysisResult,
        BaselineRecord,
        SignalAsset,
        MonitoringSession,
        ResearchExperiment,
        Dataset,
        Profile,
        User,
    ):
        db.execute(delete(model))
    db.commit()
    seed_all(db)


if __name__ == "__main__":
    import argparse

    from .db import SessionLocal, init_db

    parser = argparse.ArgumentParser(description="Seed AuraSense demo data")
    parser.add_argument("--reset", action="store_true")
    args = parser.parse_args()
    init_db()
    with SessionLocal() as session:
        if args.reset:
            reset_and_seed(session)
        else:
            seed_if_needed(session)
    print("Seed complete.")
