"""Monitoring session endpoints (simulated live stream)."""
from __future__ import annotations

from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import desc, select
from sqlalchemy.orm import Session

from ..db import get_db
from ..deps import get_current_user
from ..models import AnalysisResult, MonitoringSession, User
from ..schemas import SessionCreateIn, SessionTickIn
from ..services import live
from ..services.serializers import analysis_dict, session_dict
from ..services.simulation import SCENARIOS

router = APIRouter(prefix="/api/sessions", tags=["monitoring"])


def _get_session(db: Session, user: User, session_id: str) -> MonitoringSession:
    session = db.get(MonitoringSession, session_id)
    if session is None or session.user_id != user.id:
        raise HTTPException(status_code=404, detail="Monitoring session not found.")
    return session


@router.get("/scenarios")
def scenarios() -> dict:
    return {
        "scenarios": [
            {
                "key": key,
                "label": value["label"],
                "description": value["description"],
                "expected_pattern": value["expected_pattern"],
                "is_simulation": True,
            }
            for key, value in SCENARIOS.items()
        ],
        "notice": "All scenarios are synthetic illustrations generated by the server; they are not measurements from a person.",
    }


@router.post("", status_code=201)
def create_session(
    payload: SessionCreateIn, user: User = Depends(get_current_user), db: Session = Depends(get_db)
) -> dict:
    active = db.scalars(
        select(MonitoringSession)
        .where(MonitoringSession.user_id == user.id)
        .where(MonitoringSession.status.in_(["active", "paused"]))
    ).first()
    if active is not None:
        active.status = "aborted"
        active.ended_at = datetime.now(timezone.utc)
        db.commit()
    session = MonitoringSession(
        user_id=user.id,
        scenario=payload.scenario,
        data_source="simulated",
        status="active",
        is_simulation=True,
        is_demo=user.is_demo,
    )
    db.add(session)
    db.commit()
    db.refresh(session)
    return {
        "session": session_dict(session),
        "scenario": {
            "key": payload.scenario,
            **{k: SCENARIOS[payload.scenario][k] for k in ("label", "description", "expected_pattern")},
        },
        "is_simulation": True,
        "notice": "Simulated physiological stream. Not a real measurement.",
    }


@router.get("")
def list_sessions(
    limit: int = 25, user: User = Depends(get_current_user), db: Session = Depends(get_db)
) -> dict:
    limit = max(1, min(limit, 100))
    sessions = db.scalars(
        select(MonitoringSession)
        .where(MonitoringSession.user_id == user.id)
        .order_by(desc(MonitoringSession.started_at))
        .limit(limit)
    ).all()
    payload = []
    for session in sessions:
        analysis = db.scalars(
            select(AnalysisResult)
            .where(AnalysisResult.session_id == session.id)
            .order_by(desc(AnalysisResult.created_at))
        ).first()
        payload.append(session_dict(session, analysis_dict(analysis, include_features=False) if analysis else None))
    return {"sessions": payload}


@router.get("/{session_id}")
def get_session(
    session_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)
) -> dict:
    session = _get_session(db, user, session_id)
    analysis = db.scalars(
        select(AnalysisResult)
        .where(AnalysisResult.session_id == session.id)
        .order_by(desc(AnalysisResult.created_at))
    ).first()
    return {
        "session": session_dict(session),
        "analysis": analysis_dict(analysis) if analysis else None,
        "scenario": {
            "key": session.scenario,
            **{k: SCENARIOS.get(session.scenario, SCENARIOS["resting"])[k] for k in ("label", "description", "expected_pattern")},
        },
    }


@router.post("/{session_id}/tick")
def tick(
    session_id: str,
    payload: SessionTickIn,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> dict:
    session = _get_session(db, user, session_id)
    return live.tick(db, user, session, payload.tick_seconds)


@router.post("/{session_id}/pause")
def pause(session_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)) -> dict:
    session = _get_session(db, user, session_id)
    if session.status != "active":
        raise HTTPException(status_code=400, detail="Only an active session can be paused.")
    session.status = "paused"
    db.commit()
    return {"session": session_dict(session)}


@router.post("/{session_id}/resume")
def resume(session_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)) -> dict:
    session = _get_session(db, user, session_id)
    if session.status != "paused":
        raise HTTPException(status_code=400, detail="Only a paused session can be resumed.")
    session.status = "active"
    db.commit()
    return {"session": session_dict(session)}


@router.post("/{session_id}/stop")
def stop(session_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)) -> dict:
    session = _get_session(db, user, session_id)
    if session.status not in ("active", "paused"):
        raise HTTPException(status_code=400, detail="This session has already ended.")
    analysis, _ = live.stop(db, user, session)
    db.refresh(session)
    return {
        "session": session_dict(session),
        "analysis": analysis_dict(analysis),
        "notice": "Simulated session saved. The estimate is based on synthetic signals.",
    }


@router.delete("/{session_id}")
def delete_session(
    session_id: str, user: User = Depends(get_current_user), db: Session = Depends(get_db)
) -> dict:
    session = _get_session(db, user, session_id)
    for analysis in db.scalars(select(AnalysisResult).where(AnalysisResult.session_id == session.id)).all():
        analysis.session_id = None
    db.delete(session)
    db.commit()
    return {"ok": True}
